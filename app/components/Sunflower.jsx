    const rects = Array.from(flowerSvg.querySelectorAll("rect"));
    const cursor = { x: 0, y: 0 };
    const mouse = { x: 0, y: 0 };
    let isMouseOver = false;
    let targetIsMouseOver = false;
    let hoverBlend = 0;
    let rafId = null;

    // Pre-calculate rect centers once
    const rectData = rects.map((rect) => {
      const x = parseFloat(rect.getAttribute("x")) || 0;
      const y = parseFloat(rect.getAttribute("y")) || 0;
      const width = parseFloat(rect.getAttribute("width")) || 0;
      const height = parseFloat(rect.getAttribute("height")) || 0;

      return {
        element: rect,
        centerX: x + width / 2,
        centerY: y + height / 2,
      };
    });

    // Set initial styles once
    rectData.forEach(({ element, centerX, centerY }) => {
      element.style.transformOrigin = `${centerX}px ${centerY}px`;
    });

    const dist = (a, b) => {
      const dx = b.x - a.x;
      const dy = b.y - a.y;
      return Math.sqrt(dx * dx + dy * dy);
    };

    const handleMouseMove = (e) => {
      cursor.x = e.clientX;
      cursor.y = e.clientY;
      targetIsMouseOver = true;
    };

    const handleMouseLeave = () => {
      targetIsMouseOver = false;
    };

    const handleTouchMove = (e) => {
      if (e.touches.length > 0) {
        cursor.x = e.touches[0].clientX;
        cursor.y = e.touches[0].clientY;
        targetIsMouseOver = true;
      }
    };

    const handleTouchEnd = () => {
      targetIsMouseOver = false;
    };

    flowerSvg.addEventListener("mousemove", handleMouseMove);
    flowerSvg.addEventListener("mouseleave", handleMouseLeave);
    flowerSvg.addEventListener("touchmove", handleTouchMove, {
      passive: true,
    });
    flowerSvg.addEventListener("touchend", handleTouchEnd);
    flowerSvg.addEventListener("touchcancel", handleTouchEnd);

    // Initialize center position
    const svgRect = flowerSvg.getBoundingClientRect();
    cursor.x = svgRect.left + svgRect.width / 2;
    cursor.y = svgRect.top + svgRect.height / 2;
    mouse.x = cursor.x;
    mouse.y = cursor.y;

